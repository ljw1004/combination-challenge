import type {StoryAnalysis} from './analyze.ts';
import {corpusSummary} from './analyze.ts';
import type {Distribution} from './statistics.ts';

export type SourcedAnalysis = StoryAnalysis & {sha256: string};
const number = (value: number | null) => value === null ? '—' : Number(value.toFixed(2)).toLocaleString('en-US');
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');
const stats = (d: Distribution) => `${number(d.min)} / ${number(d.max)} / ${number(d.avg)} / ${number(d.median)}`;

export function markdownReport(stories: readonly SourcedAnalysis[], definitionsLink: string): string {
  const lines = [
    '# Story structure comparison', '',
    `Generated by the reusable story analyzer. [Definitions, commands and limitations](${definitionsLink}).`, '',
    'Exactly ten measures: three scale measures below, then seven distributions. In every distribution cell the order is **min / max / avg / median**. All means are arithmetic; displayed values are rounded to two decimals.', '',
    'Construction values are structural maxima across recipes and referenced fitted forms, not guaranteed playable plans. Chapter measurements come from one completed, deterministic engine replay per story, not fresh playtesting or exhaustive route search.', '',
    '## 1–3. Scale', '',
    '| Story | 1. Items (primitive + derived) | 2. Rules (explicit + fitting) | 3. Chapters (non-ending + ending) |',
    '|---|---:|---:|---:|',
  ];
  for (const s of stories) {
    const t = s.totals;
    lines.push(`| ${cell(s.title)} | ${t.items} (${t.primitives} + ${t.derived}) | ${t.rules} (${t.explicitRules} + ${t.installations}) | ${t.chapters} (${t.playableChapters} + ${t.chapters - t.playableChapters}) |`);
  }
  lines.push('', 'These are totals within a story. Their distribution is across the selected stories, with one vote per story; there is no useful within-story average of a single total.', '',
    '| Measure | Stories | Min / max / avg / median |', '|---|---:|---:|');
  for (const [key, d] of Object.entries(corpusSummary(stories))) lines.push(`| ${key} | ${d.n} | ${stats(d)} |`);

  lines.push('', '## 4–6. Construction', '',
    'Each identity contributes one sample, including primitives. Each metric independently takes its maximum over that identity’s referenced forms and alternative recipes. Expanded trees repeat shared subtrees; they are not counts of distinct inventory items or of actions a player must perform.', '',
    '| Story | Items sampled | 4. Chain depth (combinations) | 5. Expanded tree nodes | 6. Primitive leaf occurrences |',
    '|---|---:|---:|---:|---:|');
  for (const s of stories) lines.push(`| ${cell(s.title)} | ${s.metrics.constructionDepth.n} | ${stats(s.metrics.constructionDepth)} | ${stats(s.metrics.constructionNodes)} | ${stats(s.metrics.primitiveLeaves)} |`);

  lines.push('', '## 7. Chapters linked by a chain', '',
    'One sample per encountered identity, using its last constructed/fitted state in the reference replay. Count distinct chapters containing combinations along a single dependency path. Supplies alone score zero; elapsed gaps and parallel branches do not add chapters.', '',
    '| Story | Encountered items | Min / max / avg / median chapters |', '|---|---:|---:|');
  for (const s of stories) lines.push(`| ${cell(s.title)} | ${s.metrics.chainChapters.n} | ${stats(s.metrics.chainChapters)} |`);

  lines.push('', '## 8–10. Chapter pacing and working set', '',
    'One sample per visited non-ending chapter, including the opening chapter and zero-combination chapters. Skipped chapters and a final chapter without goals are excluded. Board size counts available item tokens on the current chapter surface, including fitted owners and items at hotspots, but not installed components, fixed hotspots or scrollback.', '',
    '| Story | Chapters sampled | 8. New primitive supplies | 9. Accepted combinations | 10. Peak board items |',
    '|---|---:|---:|---:|---:|');
  for (const s of stories) lines.push(`| ${cell(s.title)} | ${s.metrics.newPrimitives.n} | ${stats(s.metrics.newPrimitives)} | ${stats(s.metrics.combinations)} | ${stats(s.metrics.peakBoard)} |`);

  lines.push('', '## Longest structural chains', '', 'Each example attains measure 4’s maximum. Fitted owner versions are separate steps, not new identities. These examples are dependency paths, not complete recipes or legal walkthroughs.', '');
  for (const s of stories) {
    const item = s.details.items.reduce<StoryAnalysis['details']['items'][number] | undefined>((a, b) => !a || b.depth > a.depth ? b : a, undefined);
    lines.push(`- **${s.title}** (${item?.depth ?? 0} combinations): ${item?.depthPath.join(' → ') ?? 'No items'}.`);
  }
  lines.push('', '## Inputs and replay coverage', '',
    'Hashes identify manuscript content. Re-running with a changed engine or checkpoint planner can change the reference route. Completion does not establish coverage of every item or rule, authenticity, readability, emotional impact or enjoyment.', '',
    '| Manuscript | SHA-256 | Completed replay combinations | Visited / authored chapters |', '|---|---|---:|---:|');
  for (const s of stories) lines.push(`| ${cell(s.source)} | ${s.sha256} | ${s.details.route.combinations} | ${s.details.route.visitedChapters.length} / ${s.totals.chapters} |`);
  return lines.join('\n') + '\n';
}

export function jsonReport(stories: readonly SourcedAnalysis[], details = false): string {
  return JSON.stringify({
    schemaVersion: 1,
    method: 'Structural maxima; one deterministic legal checkpoint replay. See docs/story-analysis.md.',
    corpus: corpusSummary(stories),
    stories: stories.map(s => {
      const {details: detail, ...summary} = s;
      return {...summary, replay: {completed: detail.route.completed, combinations: detail.route.combinations, visitedChapters: detail.route.visitedChapters}, ...(details ? {details: detail} : {})};
    }),
  }, null, 2) + '\n';
}
